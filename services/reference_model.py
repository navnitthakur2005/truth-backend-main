"""Reference ML model integration for TruthLens.

Loads the TF-IDF vectorizer and Logistic Regression classifier generated by
``train_model.py`` from ``backend/model/``.

Expected artifacts:
    backend/model/fake_news_model.pkl
    backend/model/tfidf_vectorizer.pkl

Labels used by the training script:
    0 = Fake
    1 = Real

Note: the current example trainer uses only a tiny toy dataset. A successful
load does not mean the model is accurate or suitable for production use.
"""

import logging
import re
from pathlib import Path
from typing import Optional, Tuple

import joblib

logger = logging.getLogger(__name__)

# Model state is loaded lazily, on the first health check or prediction.
_model = None
_vectorizer = None
_loaded = False


def _load_artifacts() -> bool:
    """Load model and vectorizer once; return whether both loaded successfully."""
    global _model, _vectorizer, _loaded

    if _loaded and _model is not None and _vectorizer is not None:
        return True

    # reference_model.py is in backend/services/, so parents[1] is backend/.
    model_dir = Path(__file__).resolve().parents[1] / "model"
    model_path = model_dir / "fake_news_model.pkl"
    vectorizer_path = model_dir / "tfidf_vectorizer.pkl"

    if not model_path.is_file() or not vectorizer_path.is_file():
        missing = [str(path) for path in (model_path, vectorizer_path) if not path.is_file()]
        logger.warning("Model artifact(s) not found: %s", ", ".join(missing))
        _model = None
        _vectorizer = None
        _loaded = False
        return False

    try:
        # Load into local variables first so a partial failure cannot leave
        # the module in a half-loaded state.
        model = joblib.load(model_path)
        vectorizer = joblib.load(vectorizer_path)

        if not callable(getattr(model, "predict", None)):
            raise TypeError("Loaded model does not provide predict()")
        if not callable(getattr(vectorizer, "transform", None)):
            raise TypeError("Loaded vectorizer does not provide transform()")

        _model = model
        _vectorizer = vectorizer
        _loaded = True
        logger.info("Loaded model artifacts from %s", model_dir)
        return True
    except Exception:
        _model = None
        _vectorizer = None
        _loaded = False
        logger.exception("Failed to load model artifacts from %s", model_dir)
        return False


def load_artifacts() -> bool:
    """Public function for explicitly loading artifacts at startup."""
    return _load_artifacts()


def clean_text(text: str) -> str:
    """Apply the same basic text cleaning used by the training script."""
    if not isinstance(text, str) or not text.strip():
        return ""

    text = text.lower()
    text = re.sub(r"http\S+|www\S+|https\S+", "", text)
    text = re.sub(r"[^a-zA-Z\s]", "", text)
    words = text.split()

    # Match training preprocessing when the NLTK English corpus is installed.
    # The trainer also skips stopword removal when the corpus is unavailable.
    try:
        from nltk.corpus import stopwords

        stop_words = set(stopwords.words("english"))
        words = [word for word in words if word not in stop_words]
    except (ImportError, LookupError, OSError):
        logger.debug("NLTK English stopwords unavailable; skipping stopword removal")

    return " ".join(words)


def predict_news(text: str) -> Tuple[Optional[str], Optional[float]]:
    """Classify text and return (``Fake``/``Real``, predicted-class probability).

    Returns ``(None, None)`` when the artifacts are unavailable, the input has
    no usable words, or prediction fails. The returned probability is the
    classifier's predicted-class probability; it is not necessarily a
    calibrated measure of factual certainty.
    """
    if not _load_artifacts():
        return None, None

    if not isinstance(text, str) or not text.strip():
        return None, None

    try:
        cleaned = clean_text(text)
        if not cleaned:
            return None, None

        features = _vectorizer.transform([cleaned])
        prediction = _model.predict(features)[0]

        # Use class labels to find the corresponding probability column rather
        # than assuming their order, while preserving the project's 0/1 scheme.
        classes = list(getattr(_model, "classes_", []))
        if not classes:
            logger.error("Loaded model does not expose classes_; cannot map prediction probability")
            return None, None

        class_index = classes.index(prediction)
        probabilities = _model.predict_proba(features)[0]
        confidence = float(probabilities[class_index])

        if prediction == 0:
            label = "Fake"
        elif prediction == 1:
            label = "Real"
        else:
            logger.error("Unexpected model label: %r", prediction)
            return None, None

        return label, confidence
    except Exception:
        logger.exception("Error during ML prediction")
        return None, None


def is_model_available() -> bool:
    """Return True if the model and vectorizer can be loaded successfully."""
    return _load_artifacts()
